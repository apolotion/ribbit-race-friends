
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import vm from "node:vm";

class GameBundleBuilder {
  static modulePaths = [
  "client/game/10-core-config.js",
  "client/game/20-models-and-state.js",
  "client/game/30-online-versus.js",
  "client/game/40-ui-navigation-audio.js",
  "client/game/50-solo-gameplay.js",
  "client/game/60-versus-gameplay.js",
  "client/game/70-rendering.js",
  "client/game/80-input-loop-startup.js"
];

  constructor(projectRoot = process.cwd()) {
    this.projectRoot = projectRoot;
    this.outputPath = resolve(projectRoot, "public/scripts/game.bundle.js");
  }

  readAndValidate(relativePath) {
    const absolutePath = resolve(this.projectRoot, relativePath);
    const source = readFileSync(absolutePath, "utf8");
    new vm.Script(source, { filename: relativePath });
    return source.trimEnd();
  }

  build() {
    const modules = GameBundleBuilder.modulePaths.map((path) => ({
      path,
      source: this.readAndValidate(path)
    }));
    const body = modules.map((module) =>
      `\n    /* ===== ${module.path} ===== */\n${module.source}`
    ).join("\n");
    const bundle = [
      `"use strict";`,
      `/* Generated by scripts/build-game.mjs. Edit client/game modules, not this file. */`,
      `function startRibbitRaceGame() {`,
      body,
      `\n}`,
      ``
    ].join("\n");
    new vm.Script(bundle, { filename: "public/scripts/game.bundle.js" });
    writeFileSync(this.outputPath, bundle, "utf8");
    return { bytes: Buffer.byteLength(bundle), modules: modules.length };
  }
}

const result = new GameBundleBuilder().build();
console.log(`Built game bundle from ${result.modules} modules (${result.bytes} bytes).`);
