import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import vm from "node:vm";

/**
 * Builds the browser runtime from small responsibility-focused source files.
 * Files are ordered by their numeric prefix, so adding a module does not require
 * editing a second hard-coded manifest.
 */
class GameBundleBuilder {
  constructor(projectRoot = process.cwd()) {
    this.projectRoot = projectRoot;
    this.sourceDirectory = resolve(projectRoot, "client/game");
    this.outputPath = resolve(projectRoot, "public/scripts/game.bundle.js");
  }

  discoverModules() {
    return readdirSync(this.sourceDirectory)
      .filter((name) => /^\d+-.+\.js$/i.test(name))
      .sort((left, right) => {
        const leftOrder = Number.parseInt(left, 10);
        const rightOrder = Number.parseInt(right, 10);
        return leftOrder - rightOrder || left.localeCompare(right);
      })
      .map((name) => `client/game/${name}`);
  }

  readAndValidate(relativePath) {
    const absolutePath = resolve(this.projectRoot, relativePath);
    const source = readFileSync(absolutePath, "utf8").trimEnd();
    new vm.Script(source, { filename: relativePath });
    return source;
  }

  compactForProduction(source) {
    // Source modules stay fully commented and readable. The generated runtime
    // drops blank lines and comment-only lines to reduce transfer and parse work
    // without changing statements, expressions, or line-internal comments.
    return source
      .split(/\r?\n/)
      .filter((line) => {
        const trimmed = line.trim();
        return trimmed && !trimmed.startsWith("//");
      })
      .join("\n");
  }

  build() {
    const modules = this.discoverModules().map((path) => ({
      path,
      source: this.readAndValidate(path)
    }));

    const body = modules
      .map(({ path, source }) =>
        `\n    /* ===== ${path} ===== */\n${this.compactForProduction(source)}`
      )
      .join("\n");

    const bundle = [
      `"use strict";`,
      `/* Generated by scripts/build-game.mjs. Edit client/game modules, not this file. */`,
      `function startRibbitRaceGame() {`,
      body,
      `\n}`,
      ``
    ].join("\n");

    new vm.Script(bundle, { filename: "public/scripts/game.bundle.js" });
    writeFileSync(this.outputPath, bundle, "utf8");

    return {
      bytes: Buffer.byteLength(bundle),
      modules: modules.length,
      largestModule: modules.reduce((largest, current) =>
        current.source.length > largest.source.length ? current : largest
      )
    };
  }
}

const result = new GameBundleBuilder().build();
console.log(
  `Built game bundle from ${result.modules} modules (${result.bytes} bytes). ` +
  `Largest source module: ${result.largestModule.path}.`
);
